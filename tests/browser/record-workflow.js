async(page)=>{
  const checks=[];
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:4176/');
  await page.evaluate(()=>localStorage.removeItem('fieldlens.history'));await page.reload();
  await page.evaluate(()=>{
    const original=URL.createObjectURL.bind(URL);
    URL.createObjectURL=blob=>{if(blob.type==='application/json')window.lastReport=blob.text();return original(blob)};
  });
  await page.getByRole('button',{name:'加载示例并查看',exact:true}).click();
  await page.locator('[data-result="0"]').focus();await page.keyboard.press('Enter');
  checks.push({issue:'keyboard_result_focus',pass:await page.locator('[data-result="0"]').evaluate(el=>el===document.activeElement)});
  await page.locator('#inspection-note').fill('原始备注');await page.locator('#save').click();
  await page.getByRole('button',{name:'检测记录',exact:true}).click();
  await page.getByRole('button',{name:'详情',exact:true}).click();
  await page.locator('[data-detail-tab="review"]').click();
  await page.locator('#record-notes').fill('复核后备注');await page.locator('#record-reviewed').check();
  await page.locator('#save-review').click();
  await page.getByRole('button',{name:'图像检测',exact:true}).click();
  checks.push({issue:'review_notes_sync',pass:await page.locator('#inspection-note').inputValue()==='复核后备注'&&await page.locator('#save').isDisabled()});
  await page.locator('#export').click();
  const workspaceReport=await page.evaluate(async()=>JSON.parse(await window.lastReport));
  checks.push({issue:'workspace_export_review_status',pass:workspaceReport.reviewed===true&&workspaceReport.notes==='复核后备注'});
  await page.getByRole('button',{name:'检测记录',exact:true}).click();
  await page.getByRole('button',{name:'详情',exact:true}).click();
  await page.locator('[data-detail-tab="review"]').click();
  await page.locator('#record-notes').fill('本次导出草稿');await page.locator('#record-reviewed').uncheck();
  await page.locator('#detail-export').click();
  const detailReport=await page.evaluate(async()=>JSON.parse(await window.lastReport));
  checks.push({issue:'detail_export_current_fields',pass:detailReport.notes==='本次导出草稿'&&detailReport.reviewed===false});
  const persisted=await page.evaluate(()=>JSON.parse(localStorage.getItem('fieldlens.history'))[0]);
  if(persisted.notes!=='复核后备注'||!persisted.reviewed)throw Error('Export must not implicitly persist draft edits');
  await page.evaluate(()=>{window.confirm=()=>true});
  await page.locator('#close-detail').click();
  await page.getByRole('button',{name:'图像检测',exact:true}).click();
  await page.locator('#inspection-note').fill('单独保留的工作台草稿');
  await page.getByRole('button',{name:'检测记录',exact:true}).click();
  await page.getByRole('button',{name:'详情',exact:true}).click();
  await page.locator('[data-detail-tab="review"]').click();
  await page.locator('#record-notes').fill('第二次复核意见');await page.locator('#save-review').click();
  await page.getByRole('button',{name:'图像检测',exact:true}).click();
  if(await page.locator('#inspection-note').inputValue()!=='单独保留的工作台草稿')throw Error('Review sync must preserve independent workspace draft');
  const fixtures=await page.evaluate(()=>localStorage.getItem('fieldlens.history'));
  await page.route('**/api/health',r=>r.fulfill({json:{ready:true,model:'audit-mock'}}));
  let held;
  await page.route('**/api/detect',r=>{held=r});
  await page.goto('http://127.0.0.1:5176/');
  await page.evaluate(data=>localStorage.setItem('fieldlens.history',data),fixtures);await page.reload();
  await page.locator('#file-input').setInputFiles('docs/mobile.png');
  await page.getByRole('button',{name:'开始检测',exact:true}).click();
  await page.getByRole('button',{name:'检测记录',exact:true}).click();
  await page.getByRole('button',{name:'详情',exact:true}).click();
  await page.locator('[data-detail-tab="review"]').click();
  await page.locator('#record-notes').fill('检测等待期间正在填写的意见');
  await held.fulfill({json:{detections:[],model:'audit-mock',elapsed_ms:10}});
  await page.locator('#toast').filter({hasText:'检测完成'}).waitFor();
  checks.push({issue:'background_completion_keeps_editor',pass:await page.locator('#record-dialog').evaluate(el=>el.open)&&await page.locator('#record-notes').count()===1&&await page.locator('#record-notes').inputValue()==='检测等待期间正在填写的意见'});
  if(await page.locator('#record-dialog').evaluate(el=>el.open))await page.locator('#save-review').click();
  await page.getByRole('button',{name:'图像检测',exact:true}).click();
  if(await page.locator('#save').isDisabled()||await page.locator('#result-count').innerText()!=='0 个区域')throw Error('Background result must remain available on return');
  await page.unrouteAll({behavior:'wait'});
  await page.evaluate(data=>sessionStorage.setItem('record-audit',JSON.stringify(data)),checks);
  const failures=checks.filter(c=>!c.pass);
  if(failures.length||errors.length)throw Error(JSON.stringify({failures,errors}));
  return checks;
}
